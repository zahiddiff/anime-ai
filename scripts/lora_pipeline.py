"""Character LoRA pipeline (runs in the sd-scripts venv).

    trainers\\sd-scripts\\venv\\Scripts\\python.exe scripts\\lora_pipeline.py prep  sumi
    trainers\\sd-scripts\\venv\\Scripts\\python.exe scripts\\lora_pipeline.py train sumi

prep : copies the curated images in characters/<name>/candidates/ into
       dataset/<repeats>_<trigger>/, auto-tags them with WD14 (booru tags), puts the trigger word first and
       prunes the identity tags listed in character.json so the trigger word absorbs them.
train: writes training_config.toml (8 GB-safe settings) and runs sdxl_train_network.py.
       LoRA files land in characters/<name>/lora/.
"""
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SDS = ROOT / "trainers" / "sd-scripts"
PY = SDS / "venv" / "Scripts" / "python.exe"
BASE_CKPT = ROOT / "comfyui" / "ComfyUI" / "models" / "checkpoints" / "NoobAI-XL-v1.1.safetensors"
COMFY_LORAS = ROOT / "comfyui" / "ComfyUI" / "models" / "loras"
TAGGER = "SmilingWolf/wd-vit-tagger-v3"
IMG_EXT = {".png", ".jpg", ".jpeg", ".webp"}
# WD14 tags that are wrong for our generated images
JUNK_TAGS = {"virtual youtuber", "signature", "watermark", "artist name", "web address", "patreon username"}
TARGET_STEPS = 1500  # ~1500 steps is a good default for a 20-40 image character LoRA at rank 16


def load(name):
    d = ROOT / "project" / "characters" / name
    return d, json.loads((d / "character.json").read_text(encoding="utf-8"))


def repeats_for(n_images, epochs=10):
    return max(1, round(TARGET_STEPS / (n_images * epochs)))


def prep(name):
    d, sheet = load(name)
    imgs = sorted(p for p in (d / "candidates").iterdir() if p.suffix.lower() in IMG_EXT)
    if not imgs:
        sys.exit("no candidates left - generate some first")
    reps = repeats_for(len(imgs))
    ds_root = d / "dataset"
    if ds_root.exists():
        shutil.rmtree(ds_root)
    ds = ds_root / f"{reps}_{sheet['trigger']}"
    ds.mkdir(parents=True)
    for p in imgs:
        shutil.copy(p, ds / p.name)
    print(f"{len(imgs)} images x {reps} repeats -> {ds}")

    subprocess.run([str(PY), "finetune/tag_images_by_wd14_tagger.py", str(ds), "--onnx", "--repo_id", TAGGER,
                    "--model_dir", str(ROOT / "trainers" / "wd14"), "--batch_size", "4",
                    "--general_threshold", "0.35", "--character_threshold", "0.85", "--remove_underscore",
                    "--caption_extension", ".txt"], cwd=SDS, check=True)

    prune = {t.lower() for t in sheet.get("prune_tags_from_captions", [])} | JUNK_TAGS
    for txt in ds.glob("*.txt"):
        tags = [t.strip() for t in txt.read_text(encoding="utf-8").split(",") if t.strip()]
        tags = [t for t in tags if t.lower() not in prune and t != sheet["trigger"]]
        txt.write_text(", ".join([sheet["trigger"]] + tags), encoding="utf-8")
    sample = next(ds.glob("*.txt"))
    print("example caption:", sample.read_text(encoding="utf-8"))


def train(name, epochs=10):
    d, sheet = load(name)
    ds_root = d / "dataset"
    out = d / "lora"
    out.mkdir(exist_ok=True)
    cfg = f'''# 8 GB-safe SDXL LoRA settings (RTX 4060 Laptop, 16 GB RAM) - generated by lora_pipeline.py
pretrained_model_name_or_path = "{BASE_CKPT.as_posix()}"
train_data_dir = "{ds_root.as_posix()}"
output_dir = "{out.as_posix()}"
output_name = "{name}_v1"
logging_dir = "{(d / 'logs').as_posix()}"
caption_extension = ".txt"
# no shuffle_caption: sd-scripts forbids it together with cache_text_encoder_outputs (the bigger VRAM win)

resolution = "1024,1024"
enable_bucket = true
min_bucket_reso = 640
max_bucket_reso = 1536
bucket_reso_steps = 64
bucket_no_upscale = true

network_module = "networks.lora"
network_dim = 16
network_alpha = 8
network_train_unet_only = true        # SDXL text encoders are not trained -> big VRAM saving

optimizer_type = "AdamW8bit"
learning_rate = 1e-4
unet_lr = 1e-4
lr_scheduler = "cosine"
lr_warmup_steps = 50
min_snr_gamma = 5

train_batch_size = 1
max_train_epochs = {epochs}
save_every_n_epochs = 2
save_model_as = "safetensors"
save_precision = "fp16"
mixed_precision = "bf16"
fp8_base = true                       # base UNet in fp8: ~2.5 GB instead of 5 GB
gradient_checkpointing = true
sdpa = true
cache_latents = true
cache_latents_to_disk = true
cache_text_encoder_outputs = true
cache_text_encoder_outputs_to_disk = true
max_data_loader_n_workers = 1
persistent_data_loader_workers = true
seed = 42
'''
    cfg_path = d / "training_config.toml"
    cfg_path.write_text(cfg, encoding="utf-8")
    cmd = [str(SDS / "venv" / "Scripts" / "accelerate.exe"), "launch", "--num_cpu_threads_per_process", "1",
           "--num_processes", "1", "--num_machines", "1", "--mixed_precision", "bf16", "--dynamo_backend", "no",
           "sdxl_train_network.py", "--config_file", str(cfg_path)]
    print(" ".join(cmd))
    # sd-scripts prints Japanese messages; a redirected Windows console (cp1252) crashes on them
    env = {**os.environ, "PYTHONUTF8": "1", "PYTHONIOENCODING": "utf-8"}
    subprocess.run(cmd, cwd=SDS, check=True, env=env)
    COMFY_LORAS.mkdir(exist_ok=True)
    for f in out.glob("*.safetensors"):
        shutil.copy(f, COMFY_LORAS / f.name)
    print("copied LoRAs to", COMFY_LORAS)


if __name__ == "__main__":
    cmd, name = sys.argv[1], sys.argv[2]
    {"prep": prep, "train": train}[cmd](name)
